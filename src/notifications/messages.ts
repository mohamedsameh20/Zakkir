/** A message for the athan (or, with isPre, the reminder before it). */
export function pickMessage(prayerName: string, isPre = false, random: () => number = Math.random): NotificationMessage {
  if (isPre) {
    const idx = Math.floor(random() * PRE_PRAYER_MESSAGES.length);
    return PRE_PRAYER_MESSAGES[idx];
  }
  const list = PRAYER_MESSAGES[prayerName] || [];
  if (!list.length) {
    const localized = PRAYER_NAMES_AR[prayerName] || prayerName;
    return { title: `صلاة ${localized}`, body: `حان الآن موعد صلاة ${localized}` };
  }
  const idx = Math.floor(random() * list.length);
  return list[idx];
}
